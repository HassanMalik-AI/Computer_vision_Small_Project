import cv2

img=cv2.imread("image.png")
imgray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
t,thresh1 = cv2.threshold(imgray,127,255,cv2.THRESH_BINARY)
t,thresh2 = cv2.threshold(imgray,127,255,cv2.THRESH_BINARY_INV)
t,thresh3 = cv2.threshold(imgray,127,255,cv2.THRESH_TRUNC)
t,thresh4 = cv2.threshold(imgray,127,255,cv2.THRESH_TOZERO)
t,thresh5 = cv2.threshold(imgray,127,255,cv2.THRESH_TOZERO_INV)
cv2.imshow("image",img)
cv2.imshow("imagegray",imgray)
cv2.imshow("thresh1",thresh1)
cv2.imshow("thresh2",thresh2)
cv2.imshow("thresh3",thresh3)
cv2.imshow("thresh4",thresh4)
cv2.imshow("thresh5",thresh5)
cv2.waitKey(0)
cv2.destroyAllWindows()